function set_solution(model, solution, x, n, knapsacks)
    for k in 1:knapsacks
        for i in 1:n
            if i in solution[k]
                @constraint(model, x[i,k] == 1)
            else
                @constraint(model, x[i,k] == 0)
            end
        end
    end
end
